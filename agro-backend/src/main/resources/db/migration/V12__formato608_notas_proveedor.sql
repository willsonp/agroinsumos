-- =====================================================================
-- V12: Formato 608 (comprobantes anulados) y notas de crédito / débito de suplidores (CxP)
-- Origen: notacreditocxp, notadebitocxp (no enlazadas a la compra en el legado).
-- =====================================================================

-- NCF anulados a reportar en el 608 (Norma General 07-2018). En facturación electrónica los e-CF emitidos
-- no se anulan (se emite e-CF 34); aquí se registran NCF preimpresos / de serie B y e-NCF no utilizados.
CREATE TABLE comprobante_anulado (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id       BIGINT       NOT NULL REFERENCES compania(id),
    ncf               VARCHAR(19)  NOT NULL,
    fecha_comprobante DATE         NOT NULL,
    fecha_anulacion   DATE         NOT NULL,
    tipo_anulacion    VARCHAR(2)   NOT NULL CHECK (tipo_anulacion IN ('01','02','03','04','05','06','07','08','09','10')),
    motivo            VARCHAR(200),
    usuario_id        BIGINT       REFERENCES usuario(id),
    creado_en         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_comprobante_anulado UNIQUE (compania_id, ncf)
);
CREATE INDEX ix_comprobante_anulado_fecha ON comprobante_anulado (compania_id, fecha_anulacion);

-- Notas del suplidor que modifican una compra: crédito (B04/E34: devolución, descuento) o débito (B03/E33: cargos)
CREATE TABLE nota_proveedor (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id       BIGINT        NOT NULL REFERENCES compania(id),
    numero            BIGINT        NOT NULL,
    tipo              VARCHAR(7)    NOT NULL CHECK (tipo IN ('CREDITO','DEBITO')),
    proveedor_id      BIGINT        NOT NULL REFERENCES proveedor(id),
    compra_id         BIGINT        NOT NULL REFERENCES compra(id),
    fecha             DATE          NOT NULL,
    ncf               VARCHAR(19),                  -- comprobante emitido por el suplidor
    concepto          VARCHAR(200)  NOT NULL,
    subtotal          NUMERIC(18,2) NOT NULL CHECK (subtotal >= 0),
    itbis             NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (itbis >= 0),
    total             NUMERIC(18,2) NOT NULL CHECK (total > 0),
    devuelve_inventario BOOLEAN     NOT NULL DEFAULT FALSE,
    estado            VARCHAR(8)    NOT NULL DEFAULT 'EMITIDA' CHECK (estado IN ('EMITIDA','ANULADA')),
    anulado_en        TIMESTAMPTZ,
    motivo_anulacion  VARCHAR(200),
    usuario_id        BIGINT        REFERENCES usuario(id),
    actualizado_en    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_por   VARCHAR(45),
    CONSTRAINT uk_nota_proveedor_numero UNIQUE (compania_id, numero)
);
CREATE INDEX ix_nota_proveedor_compra ON nota_proveedor (compra_id);
CREATE UNIQUE INDEX uk_nota_proveedor_ncf ON nota_proveedor (compania_id, proveedor_id, ncf) WHERE ncf IS NOT NULL AND estado = 'EMITIDA';

-- Devolución de mercancía al suplidor (solo notas de crédito)
CREATE TABLE nota_proveedor_linea (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nota_id          BIGINT        NOT NULL REFERENCES nota_proveedor(id) ON DELETE CASCADE,
    compra_linea_id  BIGINT        NOT NULL REFERENCES compra_linea(id),
    articulo_id      BIGINT        NOT NULL REFERENCES articulo(id),
    cantidad         NUMERIC(14,3) NOT NULL CHECK (cantidad > 0),
    importe          NUMERIC(18,2) NOT NULL,
    itbis            NUMERIC(18,2) NOT NULL,
    costo_unitario   NUMERIC(18,4) NOT NULL       -- costo final de la compra (sale del inventario a este costo)
);

