-- =====================================================================
-- V20: Lotes y fechas de vencimiento (agroquímicos, semillas, medicamentos veterinarios)
-- El sistema anterior no lo manejaba. Solo los artículos marcados controlan lotes; el resto no cambia.
-- =====================================================================
ALTER TABLE articulo ADD COLUMN maneja_vencimiento BOOLEAN NOT NULL DEFAULT FALSE;

-- Existencia por lote y almacén. numero '' = sin número de lote; fecha NULL = lote sin fecha (entradas sin dato).
CREATE TABLE lote (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id        BIGINT        NOT NULL REFERENCES compania(id),
    articulo_id        BIGINT        NOT NULL REFERENCES articulo(id),
    almacen_id         BIGINT        NOT NULL REFERENCES almacen(id),
    numero             VARCHAR(40)   NOT NULL DEFAULT '',
    fecha_vencimiento  DATE,
    cantidad_recibida  NUMERIC(14,3) NOT NULL DEFAULT 0,
    existencia         NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (existencia >= 0),
    creado_en          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uk_lote UNIQUE NULLS NOT DISTINCT (articulo_id, almacen_id, numero, fecha_vencimiento)
);
CREATE INDEX ix_lote_vence ON lote (compania_id, fecha_vencimiento) WHERE existencia > 0;
CREATE INDEX ix_lote_articulo ON lote (articulo_id, almacen_id);

-- Qué lotes movió cada documento (para revertir anulaciones y devoluciones al lote de origen)
CREATE TABLE lote_movimiento (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id          BIGINT        NOT NULL REFERENCES lote(id),
    movimiento_id    BIGINT        REFERENCES inventario_movimiento(id),
    documento_tipo   VARCHAR(30)   NOT NULL,
    documento_id     BIGINT        NOT NULL,
    referencia_tipo  VARCHAR(30),               -- documento original (p.ej. la factura de una devolución)
    referencia_id    BIGINT,
    cantidad         NUMERIC(14,3) NOT NULL CHECK (cantidad <> 0),   -- + entra al lote, - sale
    creado_en        TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX ix_lote_mov_doc ON lote_movimiento (documento_tipo, documento_id);
CREATE INDEX ix_lote_mov_ref ON lote_movimiento (referencia_tipo, referencia_id) WHERE referencia_tipo IS NOT NULL;
CREATE INDEX ix_lote_mov_lote ON lote_movimiento (lote_id);

ALTER TABLE compra_linea ADD COLUMN lote VARCHAR(40), ADD COLUMN fecha_vencimiento DATE;
