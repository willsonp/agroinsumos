-- =====================================================================
-- V1: Núcleo de seguridad y compañía
-- Origen MySQL: compania, usuario, main_menu, sub_menu, detalle_opciones_menu
-- Cambios respecto a MySQL:
--   * Identificadores BIGINT IDENTITY y nombres snake_case.
--   * estado/nivel con CHECK (antes VARCHAR libre).
--   * "usuario" (nombre del PC que modificó) -> actualizado_por (usuario autenticado).
--   * ON UPDATE CURRENT_TIMESTAMP no existe en PostgreSQL: lo gestiona JPA Auditing.
--   * userpassw (SHA-1 sin sal) -> password_hash (formato DelegatingPasswordEncoder).
--   * Nuevas tablas: refresh_token, usuario_identidad_externa (OAuth2).
-- =====================================================================

CREATE TABLE compania (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                      VARCHAR(150) NOT NULL,
    nombre_comercial            VARCHAR(150),
    direccion                   VARCHAR(200),
    rnc                         VARCHAR(11)  NOT NULL,
    correo                      VARCHAR(100),
    representante               VARCHAR(100),
    sitio_web                   VARCHAR(100),
    ruta_imagen                 VARCHAR(255),
    itbis                       NUMERIC(5,2) NOT NULL DEFAULT 18.00,
    afp                         NUMERIC(5,2) NOT NULL DEFAULT 0,
    ars                         NUMERIC(5,2) NOT NULL DEFAULT 0,
    arl                         NUMERIC(5,2) NOT NULL DEFAULT 0,
    infotep                     NUMERIC(5,2) NOT NULL DEFAULT 0,
    acepta_contabilidad         BOOLEAN      NOT NULL DEFAULT FALSE,
    -- Cuentas contables por defecto (FK a catalogo cuando se migre Contabilidad)
    cuenta_caja_general         VARCHAR(12),
    cuenta_itbis_retenido       VARCHAR(12),
    cuenta_isr                  VARCHAR(12),
    cuenta_devolucion           VARCHAR(12),
    cuenta_itbis_adelantado     VARCHAR(12),
    cuenta_descuento_venta      VARCHAR(12),
    cuenta_itbis_venta          VARCHAR(12),
    cuenta_ingresos             VARCHAR(12),
    estado                      VARCHAR(1)      NOT NULL DEFAULT 'A' CHECK (estado IN ('A','I')),
    actualizado_en              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actualizado_por             VARCHAR(45),
    CONSTRAINT uk_compania_rnc UNIQUE (rnc)
);

CREATE TABLE usuario (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id         BIGINT       NOT NULL REFERENCES compania(id),
    cedula              VARCHAR(11),
    nombre              VARCHAR(45)  NOT NULL,
    apellidos           VARCHAR(45),
    direccion           VARCHAR(200),
    username            VARCHAR(45)  NOT NULL,
    password_hash       VARCHAR(100),           -- NULL = solo login social
    nivel               VARCHAR(1)      NOT NULL DEFAULT 'U' CHECK (nivel IN ('A','S','U','O')),
    sexo                VARCHAR(1)      CHECK (sexo IN ('M','F')),
    correo              VARCHAR(100),
    ruta_imagen         VARCHAR(255),
    turno_id            INTEGER      DEFAULT 1, -- FK a turno al migrar Caja
    estado              VARCHAR(1)      NOT NULL DEFAULT 'A' CHECK (estado IN ('A','I')),
    intentos_fallidos   INTEGER      NOT NULL DEFAULT 0,
    bloqueado_hasta     TIMESTAMPTZ,
    ultimo_acceso       TIMESTAMPTZ,
    actualizado_en      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actualizado_por     VARCHAR(45),
    version             BIGINT       NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX uk_usuario_username ON usuario (lower(username));
CREATE UNIQUE INDEX uk_usuario_correo   ON usuario (lower(correo)) WHERE correo IS NOT NULL;
CREATE INDEX ix_usuario_compania        ON usuario (compania_id);

CREATE TABLE main_menu (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_modulo   VARCHAR(100) NOT NULL,
    codigo          VARCHAR(60)  NOT NULL UNIQUE,  -- antes Obj_Contenedor (nombre del panel Swing)
    orden           INTEGER      NOT NULL DEFAULT 0,
    estado          VARCHAR(1)      NOT NULL DEFAULT 'A' CHECK (estado IN ('A','I')),
    actualizado_en  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE sub_menu (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    main_menu_id    BIGINT       NOT NULL REFERENCES main_menu(id),
    nombre_opcion   VARCHAR(100) NOT NULL,
    codigo          VARCHAR(60)  NOT NULL UNIQUE,  -- antes Nombre_ObjHijo; ahora código de permiso
    ruta_frontend   VARCHAR(150),
    orden           INTEGER      NOT NULL DEFAULT 0,
    estado          VARCHAR(1)      NOT NULL DEFAULT 'A' CHECK (estado IN ('A','I')),
    actualizado_en  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_sub_menu_main ON sub_menu (main_menu_id);

CREATE TABLE detalle_opciones_menu (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sub_menu_id  BIGINT  NOT NULL REFERENCES sub_menu(id) ON DELETE CASCADE,
    usuario_id   BIGINT  NOT NULL REFERENCES usuario(id)  ON DELETE CASCADE,
    permitido    BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_opcion_usuario UNIQUE (sub_menu_id, usuario_id)
);
CREATE INDEX ix_opciones_usuario ON detalle_opciones_menu (usuario_id);

-- Refresh tokens opacos (solo se guarda el hash SHA-256), con rotación
CREATE TABLE refresh_token (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    BIGINT       NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    token_hash    VARCHAR(64)     NOT NULL UNIQUE,
    familia       UUID         NOT NULL,       -- cadena de rotación (detección de reutilización)
    creado_en     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expira_en     TIMESTAMPTZ  NOT NULL,
    revocado_en   TIMESTAMPTZ,
    ip            VARCHAR(45),
    user_agent    VARCHAR(255)
);
CREATE INDEX ix_refresh_usuario ON refresh_token (usuario_id);
CREATE INDEX ix_refresh_familia ON refresh_token (familia);

-- Vínculo usuario <-> proveedor OAuth2/OIDC (Google, Microsoft, ...)
CREATE TABLE usuario_identidad_externa (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    BIGINT       NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    proveedor     VARCHAR(30)  NOT NULL,
    sujeto        VARCHAR(255) NOT NULL,
    correo        VARCHAR(100),
    vinculado_en  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_identidad UNIQUE (proveedor, sujeto)
);
