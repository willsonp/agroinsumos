-- =====================================================================
-- V2: Facturación Electrónica DGII (e-CF)
-- Reemplaza tablancf (TipoNCF/secuencia/Limite/Prefijo) para comprobantes
-- electrónicos. e-NCF = 'E' + tipo (2) + secuencia (10) = 13 caracteres.
-- =====================================================================

CREATE TABLE ecf_secuencia (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id         BIGINT      NOT NULL REFERENCES compania(id),
    tipo_ecf            SMALLINT    NOT NULL CHECK (tipo_ecf IN (31,32,33,34,41,43,44,45,46,47)),
    secuencia_desde     BIGINT      NOT NULL CHECK (secuencia_desde >= 1),
    secuencia_hasta     BIGINT      NOT NULL CHECK (secuencia_hasta <= 9999999999),
    ultima_usada        BIGINT      NOT NULL DEFAULT 0,
    fecha_vencimiento   DATE        NOT NULL,
    activa              BOOLEAN     NOT NULL DEFAULT TRUE,
    actualizado_en      TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_por     VARCHAR(45),
    version             BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT ck_rango CHECK (secuencia_hasta >= secuencia_desde)
);
-- Solo un rango activo por compañía y tipo
CREATE UNIQUE INDEX uk_ecf_secuencia_activa ON ecf_secuencia (compania_id, tipo_ecf) WHERE activa;

CREATE TABLE ecf_documento (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id             BIGINT        NOT NULL REFERENCES compania(id),
    tipo_ecf                SMALLINT      NOT NULL,
    encf                    VARCHAR(13)   NOT NULL,
    fecha_emision           DATE          NOT NULL,
    rnc_comprador           VARCHAR(11),
    razon_social_comprador  VARCHAR(150),
    monto_gravado           NUMERIC(18,2) NOT NULL DEFAULT 0,
    monto_exento            NUMERIC(18,2) NOT NULL DEFAULT 0,
    total_itbis             NUMERIC(18,2) NOT NULL DEFAULT 0,
    monto_total             NUMERIC(18,2) NOT NULL,
    encf_modificado         VARCHAR(13),
    origen_tipo             VARCHAR(30),   -- p.ej. FACTURA, DEVOLUCION
    origen_id               BIGINT,
    es_resumen_consumo      BOOLEAN       NOT NULL DEFAULT FALSE,  -- e-CF 32 < 250,000 -> RFCE
    estado                  VARCHAR(25)   NOT NULL,
    codigo_seguridad        VARCHAR(6),
    fecha_hora_firma        TIMESTAMP,
    xml_firmado             TEXT          NOT NULL,
    xml_rfce_firmado        TEXT,
    track_id                VARCHAR(64),
    secuencia_utilizada     BOOLEAN,
    mensajes_dgii           JSONB,
    intentos_envio          INTEGER       NOT NULL DEFAULT 0,
    ultimo_error            VARCHAR(1000),
    enviado_en              TIMESTAMPTZ,
    creado_en               TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_en          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_por         VARCHAR(45),
    version                 BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_ecf_encf UNIQUE (compania_id, encf),
    CONSTRAINT ck_ecf_estado CHECK (estado IN ('FIRMADO','ENVIADO','EN_PROCESO','ACEPTADO',
                                               'ACEPTADO_CONDICIONAL','RECHAZADO','ERROR_ENVIO'))
);
CREATE INDEX ix_ecf_estado ON ecf_documento (estado) WHERE estado IN ('FIRMADO','ENVIADO','EN_PROCESO','ERROR_ENVIO');
CREATE INDEX ix_ecf_origen ON ecf_documento (origen_tipo, origen_id);
