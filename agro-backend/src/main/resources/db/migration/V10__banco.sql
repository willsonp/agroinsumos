CREATE TABLE banco (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(60) NOT NULL UNIQUE,
    estado          VARCHAR(1)  NOT NULL DEFAULT 'A' CHECK (estado IN ('A','I')),
    actualizado_en  TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_por VARCHAR(45)
);

CREATE TABLE cuenta_bancaria (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id          BIGINT        NOT NULL REFERENCES compania(id),
    banco_id             BIGINT        NOT NULL REFERENCES banco(id),
    numero               VARCHAR(30)   NOT NULL,
    nombre               VARCHAR(60)   NOT NULL,
    tipo                 VARCHAR(10)   NOT NULL DEFAULT 'CORRIENTE' CHECK (tipo IN ('CORRIENTE','AHORRO')),
    moneda               VARCHAR(3)    NOT NULL DEFAULT 'DOP',
    saldo_inicial        NUMERIC(18,2) NOT NULL DEFAULT 0,
    fecha_saldo_inicial  DATE          NOT NULL DEFAULT current_date,
    cuenta_contable      VARCHAR(12),
    proximo_cheque       BIGINT        NOT NULL DEFAULT 1 CHECK (proximo_cheque > 0),
    estado               VARCHAR(1)    NOT NULL DEFAULT 'A' CHECK (estado IN ('A','I')),
    actualizado_en       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_por      VARCHAR(45),
    version              BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_cuenta_bancaria UNIQUE (compania_id, banco_id, numero)
);

CREATE TABLE conciliacion_bancaria (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id            BIGINT        NOT NULL REFERENCES compania(id),
    cuenta_id              BIGINT        NOT NULL REFERENCES cuenta_bancaria(id),
    fecha_corte            DATE          NOT NULL,
    saldo_banco            NUMERIC(18,2) NOT NULL,   -- según estado de cuenta del banco
    saldo_libros           NUMERIC(18,2) NOT NULL,   -- según el sistema a la fecha de corte
    depositos_transito     NUMERIC(18,2) NOT NULL DEFAULT 0,
    cheques_transito       NUMERIC(18,2) NOT NULL DEFAULT 0,
    observacion            VARCHAR(200),
    usuario_id             BIGINT        REFERENCES usuario(id),
    creado_en              TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uk_conciliacion UNIQUE (cuenta_id, fecha_corte)
);

CREATE TABLE movimiento_bancario (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id      BIGINT        NOT NULL REFERENCES compania(id),
    cuenta_id        BIGINT        NOT NULL REFERENCES cuenta_bancaria(id),
    numero           BIGINT        NOT NULL,
    fecha            DATE          NOT NULL,
    tipo             VARCHAR(25)   NOT NULL CHECK (tipo IN ('DEPOSITO','CHEQUE','TRANSFERENCIA_ENTRADA','TRANSFERENCIA_SALIDA',
                                                            'NOTA_DEBITO','NOTA_CREDITO')),
    referencia       VARCHAR(40),             -- no. cheque, no. transferencia, no. volante de depósito
    beneficiario     VARCHAR(100),
    concepto         VARCHAR(200)  NOT NULL,
    monto            NUMERIC(18,2) NOT NULL CHECK (monto > 0),
    estado           VARCHAR(10)   NOT NULL DEFAULT 'REGISTRADO' CHECK (estado IN ('REGISTRADO','ANULADO')),
    conciliacion_id  BIGINT        REFERENCES conciliacion_bancaria(id),
    origen_tipo      VARCHAR(25),             -- PAGO_PROVEEDOR, RECIBO, TRANSFERENCIA, DEPOSITO_CAJA, MANUAL
    origen_id        BIGINT,
    transferencia_par_id BIGINT     REFERENCES movimiento_bancario(id),
    anulado_en       TIMESTAMPTZ,
    motivo_anulacion VARCHAR(200),
    usuario_id       BIGINT        REFERENCES usuario(id),
    creado_en        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_en   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_por  VARCHAR(45),
    version          BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_mov_banco_numero UNIQUE (compania_id, numero)
);
CREATE INDEX ix_mov_banco_cuenta ON movimiento_bancario (cuenta_id, fecha);
CREATE INDEX ix_mov_banco_origen ON movimiento_bancario (origen_tipo, origen_id);
-- Un número de cheque no se repite en la misma cuenta (aunque el cheque se anule)
CREATE UNIQUE INDEX uk_cheque ON movimiento_bancario (cuenta_id, referencia) WHERE tipo = 'CHEQUE';

-- Pagos y cobros por cheque/transferencia indican la cuenta bancaria
ALTER TABLE pago_proveedor_forma ADD COLUMN cuenta_bancaria_id BIGINT REFERENCES cuenta_bancaria(id);
ALTER TABLE recibo_pago ADD COLUMN cuenta_bancaria_id BIGINT REFERENCES cuenta_bancaria(id);

