-- =====================================================================
-- V19: Caja chica (fondo fijo). Origen: cajachica, cajachicabalance (FrmCuadreCajaChica, RptReposicionCaja)
-- =====================================================================
CREATE TABLE caja_chica (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id        BIGINT        NOT NULL REFERENCES compania(id),
    nombre             VARCHAR(60)   NOT NULL,
    responsable_id     BIGINT        REFERENCES usuario(id),
    monto_fondo        NUMERIC(18,2) NOT NULL CHECK (monto_fondo > 0),
    saldo              NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (saldo >= 0),
    cuenta_contable    VARCHAR(14),
    estado             VARCHAR(1)    NOT NULL DEFAULT 'A' CHECK (estado IN ('A','I')),
    actualizado_en     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_por    VARCHAR(45),
    version            BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_caja_chica UNIQUE (compania_id, nombre)
);

-- Entradas (apertura / reposición) y salidas (gastos) del fondo
CREATE TABLE caja_chica_movimiento (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id          BIGINT        NOT NULL REFERENCES compania(id),
    caja_chica_id        BIGINT        NOT NULL REFERENCES caja_chica(id),
    numero               BIGINT        NOT NULL,
    fecha                DATE          NOT NULL,
    tipo                 VARCHAR(10)   NOT NULL CHECK (tipo IN ('APERTURA','GASTO','REPOSICION')),
    concepto             VARCHAR(200)  NOT NULL,
    beneficiario         VARCHAR(100),
    rnc                  VARCHAR(11),
    ncf                  VARCHAR(19),
    tipo_bien_servicio   VARCHAR(2)    DEFAULT '02',
    monto                NUMERIC(18,2) NOT NULL CHECK (monto > 0),   -- total pagado (incluye ITBIS)
    itbis                NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (itbis >= 0),
    cuenta_gasto         VARCHAR(14),                                 -- cuenta contable del gasto (opcional)
    -- Origen del dinero en aperturas/reposiciones
    forma                VARCHAR(15)   CHECK (forma IN ('EFECTIVO','CHEQUE','TRANSFERENCIA')),
    cuenta_bancaria_id   BIGINT        REFERENCES cuenta_bancaria(id),
    sesion_caja_id       BIGINT        REFERENCES caja_sesion(id),
    reposicion_id        BIGINT        REFERENCES caja_chica_movimiento(id),   -- gasto incluido en esa reposición
    estado               VARCHAR(10)   NOT NULL DEFAULT 'REGISTRADO' CHECK (estado IN ('REGISTRADO','ANULADO')),
    motivo_anulacion     VARCHAR(200),
    usuario_id           BIGINT        REFERENCES usuario(id),
    creado_en            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uk_caja_chica_mov UNIQUE (compania_id, numero)
);
CREATE INDEX ix_caja_chica_mov ON caja_chica_movimiento (caja_chica_id, fecha);

CREATE TABLE caja_chica_arqueo (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caja_chica_id    BIGINT        NOT NULL REFERENCES caja_chica(id),
    fecha            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    efectivo_contado NUMERIC(18,2) NOT NULL CHECK (efectivo_contado >= 0),
    saldo_sistema    NUMERIC(18,2) NOT NULL,
    diferencia       NUMERIC(18,2) NOT NULL,
    observacion      VARCHAR(200),
    usuario_id       BIGINT        REFERENCES usuario(id)
);

