-- =====================================================================
-- V11: Contabilidad (partida doble)
-- Origen: catalogo (cuentas), entradadiario / detalle_entradadiario (asientos manuales),
--         cntcontabilidad / detallecontabilidad y transaccionesconta (asientos de documentos),
--         compania.Cuenta* y departamento.Cuenta* (cuentas por defecto), tmpbalanza / tmpestado (reportes).
-- En el sistema anterior las cuentas se guardaban como texto en cada tabla; aquí se mantienen como código
-- (compatibles con los datos migrados) y se validan contra cuenta_contable al contabilizar.
-- =====================================================================

CREATE TABLE cuenta_contable (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id         BIGINT       NOT NULL REFERENCES compania(id),
    codigo              VARCHAR(14)  NOT NULL,
    nombre              VARCHAR(100) NOT NULL,
    tipo                VARCHAR(10)  NOT NULL CHECK (tipo IN ('ACTIVO','PASIVO','CAPITAL','INGRESO','COSTO','GASTO')),
    padre_id            BIGINT       REFERENCES cuenta_contable(id),
    nivel               INT          NOT NULL DEFAULT 1 CHECK (nivel BETWEEN 1 AND 10),
    acepta_movimiento   BOOLEAN      NOT NULL DEFAULT TRUE,   -- legacy AceptaMov: solo las cuentas de detalle
    estado              VARCHAR(1)   NOT NULL DEFAULT 'A' CHECK (estado IN ('A','I')),
    actualizado_en      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actualizado_por     VARCHAR(45),
    CONSTRAINT uk_cuenta_contable UNIQUE (compania_id, codigo)
);
CREATE INDEX ix_cuenta_contable_padre ON cuenta_contable (padre_id);

-- Cuentas por defecto de los asientos automáticos (además de las de departamento, cliente, proveedor y cuenta bancaria)
CREATE TABLE cuenta_contable_config (
    compania_id  BIGINT      NOT NULL REFERENCES compania(id),
    clave        VARCHAR(40) NOT NULL,
    codigo       VARCHAR(14) NOT NULL,
    PRIMARY KEY (compania_id, clave)
);

-- Las cuentas que ya traía la compañía (legacy compania.Cuenta*) pasan a la configuración
INSERT INTO cuenta_contable_config (compania_id, clave, codigo)
SELECT id, x.clave, x.codigo FROM compania
CROSS JOIN LATERAL (VALUES ('CAJA', cuenta_caja_general), ('ITBIS_RETENIDO_POR_CLIENTES', cuenta_itbis_retenido),
                           ('ISR_RETENIDO_POR_CLIENTES', cuenta_isr), ('DEVOLUCIONES_VENTAS', cuenta_devolucion),
                           ('ITBIS_ADELANTADO', cuenta_itbis_adelantado), ('ITBIS_POR_PAGAR', cuenta_itbis_venta),
                           ('INGRESOS_VENTAS', cuenta_ingresos)) AS x(clave, codigo)
WHERE nullif(trim(x.codigo), '') IS NOT NULL;

-- Los documentos anteriores a esta fecha no generan asientos (su contabilidad viene migrada del sistema anterior)
ALTER TABLE compania ADD COLUMN fecha_inicio_contable DATE;

CREATE TABLE periodo_contable (
    compania_id  BIGINT      NOT NULL REFERENCES compania(id),
    anio         INT         NOT NULL,
    mes          INT         NOT NULL CHECK (mes BETWEEN 1 AND 12),
    cerrado_en   TIMESTAMPTZ NOT NULL DEFAULT now(),
    cerrado_por  BIGINT      REFERENCES usuario(id),
    PRIMARY KEY (compania_id, anio, mes)
);

CREATE TABLE asiento (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id      BIGINT        NOT NULL REFERENCES compania(id),
    numero           BIGINT        NOT NULL,
    fecha            DATE          NOT NULL,
    tipo             VARCHAR(10)   NOT NULL CHECK (tipo IN ('MANUAL','AUTOMATICO')),
    origen_tipo      VARCHAR(25),             -- FACTURA, DEVOLUCION, NOTA_DEBITO, RECIBO, COMPRA, PAGO_PROVEEDOR, MOV_BANCO, EGRESO_CAJA
    origen_id        BIGINT,
    reverso          BOOLEAN       NOT NULL DEFAULT FALSE,   -- reversa del asiento de un documento anulado
    concepto         VARCHAR(200)  NOT NULL,
    total            NUMERIC(18,2) NOT NULL CHECK (total >= 0),
    estado           VARCHAR(10)   NOT NULL DEFAULT 'REGISTRADO' CHECK (estado IN ('REGISTRADO','ANULADO')),
    motivo_anulacion VARCHAR(200),
    usuario_id       BIGINT        REFERENCES usuario(id),
    creado_en        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uk_asiento_numero UNIQUE (compania_id, numero)
);
CREATE INDEX ix_asiento_fecha ON asiento (compania_id, fecha);
-- Un documento se contabiliza una sola vez (y se reversa una sola vez)
CREATE UNIQUE INDEX uk_asiento_origen ON asiento (compania_id, origen_tipo, origen_id, reverso) WHERE origen_tipo IS NOT NULL;

CREATE TABLE asiento_linea (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asiento_id   BIGINT        NOT NULL REFERENCES asiento(id) ON DELETE CASCADE,
    linea        INT           NOT NULL,
    cuenta_id    BIGINT        NOT NULL REFERENCES cuenta_contable(id),
    descripcion  VARCHAR(200),
    debito       NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (debito >= 0),
    credito      NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (credito >= 0),
    tercero_tipo VARCHAR(1)    CHECK (tercero_tipo IN ('C','P')),   -- auxiliar: cliente / proveedor (legacy ClienteSup)
    tercero_id   BIGINT,
    CONSTRAINT ck_asiento_linea_un_lado CHECK ((debito > 0 AND credito = 0) OR (credito > 0 AND debito = 0))
);
CREATE INDEX ix_asiento_linea_cuenta ON asiento_linea (cuenta_id);
CREATE INDEX ix_asiento_linea_asiento ON asiento_linea (asiento_id);

-- Contrapartida contable opcional de los movimientos bancarios manuales (cheques a terceros, cargos, créditos)
ALTER TABLE movimiento_bancario ADD COLUMN cuenta_contrapartida VARCHAR(14);

