-- ------------------------------------------------------------------ CAJA
-- Sesión de caja por cajero (legacy "caja": status A/C). Solo una abierta por usuario.
CREATE TABLE caja_sesion (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id        BIGINT        NOT NULL REFERENCES compania(id),
    numero             BIGINT        NOT NULL,
    usuario_id         BIGINT        NOT NULL REFERENCES usuario(id),
    turno_id           BIGINT        REFERENCES turno(id),
    abierta_en         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    monto_inicial      NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (monto_inicial >= 0),
    cerrada_en         TIMESTAMPTZ,
    efectivo_esperado  NUMERIC(18,2),
    efectivo_contado   NUMERIC(18,2),
    diferencia         NUMERIC(18,2),
    observacion        VARCHAR(200),
    estado             VARCHAR(10)   NOT NULL DEFAULT 'ABIERTA' CHECK (estado IN ('ABIERTA','CERRADA')),
    actualizado_en     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_por    VARCHAR(45),
    version            BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_caja_numero UNIQUE (compania_id, numero)
);
CREATE UNIQUE INDEX uk_caja_abierta ON caja_sesion (usuario_id) WHERE estado = 'ABIERTA';

-- Todo lo que entra o sale de la caja (base del cuadre por forma de pago)
CREATE TABLE caja_movimiento (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sesion_id       BIGINT        NOT NULL REFERENCES caja_sesion(id),
    fecha           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    tipo            VARCHAR(20)   NOT NULL CHECK (tipo IN ('COBRO','INGRESO','EGRESO','PAGO_PROVEEDOR','ANULACION_COBRO','ANULACION_PAGO')),
    forma_pago      VARCHAR(15)   NOT NULL CHECK (forma_pago IN ('EFECTIVO','TARJETA','CHEQUE','TRANSFERENCIA')),
    monto           NUMERIC(18,2) NOT NULL CHECK (monto > 0),   -- el signo lo da el tipo
    referencia_tipo VARCHAR(20)   NOT NULL,
    referencia_id   BIGINT        NOT NULL,
    descripcion     VARCHAR(200)
);
CREATE INDEX ix_caja_mov_sesion ON caja_movimiento (sesion_id);

-- Conteo de billetes/monedas al cierre (legacy detamonedascuadre)
CREATE TABLE caja_conteo (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sesion_id     BIGINT        NOT NULL REFERENCES caja_sesion(id) ON DELETE CASCADE,
    denominacion  NUMERIC(10,2) NOT NULL CHECK (denominacion > 0),
    cantidad      INTEGER       NOT NULL CHECK (cantidad >= 0),
    CONSTRAINT uk_conteo UNIQUE (sesion_id, denominacion)
);

-- Egresos de caja / caja chica (legacy egresocaja). rnc/ncf del comprobante del gasto (para el 606)
CREATE TABLE caja_egreso (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id     BIGINT        NOT NULL REFERENCES compania(id),
    numero          BIGINT        NOT NULL,
    sesion_id       BIGINT        NOT NULL REFERENCES caja_sesion(id),
    fecha           DATE          NOT NULL,
    beneficiario    VARCHAR(100)  NOT NULL,
    rnc             VARCHAR(11),
    ncf             VARCHAR(19),
    concepto        VARCHAR(200)  NOT NULL,
    monto           NUMERIC(18,2) NOT NULL CHECK (monto > 0),
    itbis           NUMERIC(18,2) NOT NULL DEFAULT 0,
    usuario_id      BIGINT        REFERENCES usuario(id),
    actualizado_en  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_por VARCHAR(45),
    CONSTRAINT uk_egreso_numero UNIQUE (compania_id, numero)
);

-- ------------------------------------------------------------------ CUENTAS POR COBRAR
-- Nota de débito a cliente (legacy notadebito). Emite e-CF 33 referenciando la factura.
CREATE TABLE nota_debito (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id       BIGINT        NOT NULL REFERENCES compania(id),
    numero            BIGINT        NOT NULL,
    fecha             DATE          NOT NULL,
    fecha_vencimiento DATE          NOT NULL,
    cliente_id        BIGINT        NOT NULL REFERENCES cliente(id),
    factura_id        BIGINT        NOT NULL REFERENCES factura(id),
    concepto          VARCHAR(90)   NOT NULL,
    total_itbis       NUMERIC(18,2) NOT NULL DEFAULT 0,
    total             NUMERIC(18,2) NOT NULL CHECK (total > 0),
    balance           NUMERIC(18,2) NOT NULL,
    encf              VARCHAR(13),
    ecf_documento_id  BIGINT        REFERENCES ecf_documento(id),
    estado            VARCHAR(10)   NOT NULL DEFAULT 'EMITIDA' CHECK (estado IN ('EMITIDA','PAGADA')),
    usuario_id        BIGINT        REFERENCES usuario(id),
    actualizado_en    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_por   VARCHAR(45),
    version           BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_nd_numero UNIQUE (compania_id, numero),
    CONSTRAINT ck_nd_balance CHECK (balance BETWEEN 0 AND total)
);
CREATE INDEX ix_nd_cliente ON nota_debito (cliente_id);

-- Recibo de ingreso (legacy reciboingreso): cobro de facturas de contado y de crédito
CREATE TABLE recibo (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id       BIGINT        NOT NULL REFERENCES compania(id),
    numero            BIGINT        NOT NULL,
    fecha             DATE          NOT NULL,
    cliente_id        BIGINT        NOT NULL REFERENCES cliente(id),
    sesion_caja_id    BIGINT        REFERENCES caja_sesion(id),
    concepto          VARCHAR(200),
    total_aplicado    NUMERIC(18,2) NOT NULL,   -- abonado a documentos (sin retenciones)
    total_retenciones NUMERIC(18,2) NOT NULL DEFAULT 0,
    total_recibido    NUMERIC(18,2) NOT NULL,   -- suma de pagos
    devuelta          NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (devuelta >= 0),
    estado            VARCHAR(10)   NOT NULL DEFAULT 'EMITIDO' CHECK (estado IN ('EMITIDO','ANULADO')),
    anulado_en        TIMESTAMPTZ,
    motivo_anulacion  VARCHAR(200),
    usuario_id        BIGINT        REFERENCES usuario(id),
    actualizado_en    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_por   VARCHAR(45),
    version           BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_recibo_numero UNIQUE (compania_id, numero)
);
CREATE INDEX ix_recibo_cliente ON recibo (cliente_id, fecha);

-- Aplicación del recibo a documentos (legacy detalle_recibo)
CREATE TABLE recibo_aplicacion (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recibo_id        BIGINT        NOT NULL REFERENCES recibo(id) ON DELETE CASCADE,
    documento_tipo   VARCHAR(12)   NOT NULL CHECK (documento_tipo IN ('FACTURA','NOTA_DEBITO')),
    documento_id     BIGINT        NOT NULL,
    monto            NUMERIC(18,2) NOT NULL CHECK (monto >= 0),
    retencion_itbis  NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (retencion_itbis >= 0),
    retencion_isr    NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (retencion_isr >= 0),
    CONSTRAINT ck_aplicacion_positiva CHECK (monto + retencion_itbis + retencion_isr > 0)
);
CREATE INDEX ix_recibo_apl_doc ON recibo_aplicacion (documento_tipo, documento_id);

-- Formas de pago del recibo (antes columnas PagoEfectivo/PagoTarjeta/PagoCheque)
CREATE TABLE recibo_pago (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recibo_id   BIGINT        NOT NULL REFERENCES recibo(id) ON DELETE CASCADE,
    forma_pago  VARCHAR(15)   NOT NULL CHECK (forma_pago IN ('EFECTIVO','TARJETA','CHEQUE','TRANSFERENCIA','SALDO_A_FAVOR')),
    monto       NUMERIC(18,2) NOT NULL CHECK (monto > 0),
    referencia  VARCHAR(40),   -- no. cheque, autorización de tarjeta, no. transferencia
    banco       VARCHAR(45)
);

-- ------------------------------------------------------------------ COMPRAS / CxP
CREATE TABLE compra (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id        BIGINT        NOT NULL REFERENCES compania(id),
    numero             BIGINT        NOT NULL,
    proveedor_id       BIGINT        NOT NULL REFERENCES proveedor(id),
    fecha              DATE          NOT NULL,
    ncf_proveedor      VARCHAR(19),   -- NCF/e-NCF de la factura del suplidor (606)
    condicion          VARCHAR(10)   NOT NULL CHECK (condicion IN ('CONTADO','CREDITO')),
    dias_credito       INTEGER       NOT NULL DEFAULT 0,
    fecha_vencimiento  DATE          NOT NULL,
    almacen_id         BIGINT        NOT NULL REFERENCES almacen(id),
    numero_orden       VARCHAR(30),
    comentario         VARCHAR(300),
    subtotal           NUMERIC(18,2) NOT NULL,   -- suma de importes (sin ITBIS)
    total_descuento    NUMERIC(18,2) NOT NULL DEFAULT 0,
    total_itbis        NUMERIC(18,2) NOT NULL DEFAULT 0,
    flete              NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (flete >= 0),
    total              NUMERIC(18,2) NOT NULL,
    itbis_retenido     NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (itbis_retenido >= 0),
    isr_retenido       NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (isr_retenido >= 0),
    balance            NUMERIC(18,2) NOT NULL,   -- a pagar al suplidor = total - retenciones - pagos
    estado             VARCHAR(10)   NOT NULL DEFAULT 'REGISTRADA' CHECK (estado IN ('REGISTRADA','PAGADA','ANULADA')),
    usuario_id         BIGINT        REFERENCES usuario(id),
    actualizado_en     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_por    VARCHAR(45),
    version            BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_compra_numero UNIQUE (compania_id, numero),
    CONSTRAINT ck_compra_balance CHECK (balance >= 0)
);
CREATE UNIQUE INDEX uk_compra_ncf ON compra (proveedor_id, ncf_proveedor) WHERE ncf_proveedor IS NOT NULL AND estado <> 'ANULADA';
CREATE INDEX ix_compra_proveedor ON compra (proveedor_id, fecha);

CREATE TABLE compra_linea (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compra_id       BIGINT        NOT NULL REFERENCES compra(id) ON DELETE CASCADE,
    linea           INTEGER       NOT NULL,
    articulo_id     BIGINT        NOT NULL REFERENCES articulo(id),
    cantidad        NUMERIC(14,3) NOT NULL CHECK (cantidad > 0),
    costo_unitario  NUMERIC(18,4) NOT NULL CHECK (costo_unitario >= 0),
    descuento       NUMERIC(18,2) NOT NULL DEFAULT 0,
    tasa_itbis      NUMERIC(5,2)  NOT NULL DEFAULT 0,
    importe         NUMERIC(18,2) NOT NULL,
    itbis           NUMERIC(18,2) NOT NULL,
    costo_final     NUMERIC(18,4) NOT NULL   -- costo unitario al inventario (con descuento y flete prorrateado)
);

-- Pago a proveedor (legacy pagocompra / deta_pago_compra)
CREATE TABLE pago_proveedor (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id       BIGINT        NOT NULL REFERENCES compania(id),
    numero            BIGINT        NOT NULL,
    fecha             DATE          NOT NULL,
    proveedor_id      BIGINT        NOT NULL REFERENCES proveedor(id),
    sesion_caja_id    BIGINT        REFERENCES caja_sesion(id),
    concepto          VARCHAR(200),
    total             NUMERIC(18,2) NOT NULL CHECK (total > 0),
    estado            VARCHAR(10)   NOT NULL DEFAULT 'EMITIDO' CHECK (estado IN ('EMITIDO','ANULADO')),
    anulado_en        TIMESTAMPTZ,
    motivo_anulacion  VARCHAR(200),
    usuario_id        BIGINT        REFERENCES usuario(id),
    actualizado_en    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_por   VARCHAR(45),
    CONSTRAINT uk_pago_prov_numero UNIQUE (compania_id, numero)
);

CREATE TABLE pago_proveedor_aplicacion (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pago_id    BIGINT        NOT NULL REFERENCES pago_proveedor(id) ON DELETE CASCADE,
    compra_id  BIGINT        NOT NULL REFERENCES compra(id),
    monto      NUMERIC(18,2) NOT NULL CHECK (monto > 0)
);

CREATE TABLE pago_proveedor_forma (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pago_id     BIGINT        NOT NULL REFERENCES pago_proveedor(id) ON DELETE CASCADE,
    forma_pago  VARCHAR(15)   NOT NULL CHECK (forma_pago IN ('EFECTIVO','CHEQUE','TRANSFERENCIA','TARJETA')),
    monto       NUMERIC(18,2) NOT NULL CHECK (monto > 0),
    referencia  VARCHAR(40),
    banco       VARCHAR(45)
);
