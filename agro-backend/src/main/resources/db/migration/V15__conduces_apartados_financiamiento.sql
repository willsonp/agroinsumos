-- =====================================================================
-- V15: Ventas pendientes del legado
--   Conduces (facturapro estado T → F): mercancía entregada que se factura después.
--   Apartados (apartado): abonos del cliente hacia una compra futura (anticipos).
--   Financiamiento (cuotas, facturapro financiada): plan de cuotas sobre una factura a crédito, con interés y mora.
-- =====================================================================

CREATE TABLE conduce (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id      BIGINT        NOT NULL REFERENCES compania(id),
    numero           BIGINT        NOT NULL,
    fecha            DATE          NOT NULL,
    cliente_id       BIGINT        NOT NULL REFERENCES cliente(id),
    almacen_id       BIGINT        NOT NULL REFERENCES almacen(id),
    vendedor_id      BIGINT        REFERENCES vendedor(id),
    tipo_precio      VARCHAR(10)   NOT NULL,
    comentario       VARCHAR(300),
    lugar_entrega    VARCHAR(200),
    total_estimado   NUMERIC(18,2) NOT NULL DEFAULT 0,   -- con ITBIS, a los precios del conduce
    estado           VARCHAR(10)   NOT NULL DEFAULT 'ABIERTO' CHECK (estado IN ('ABIERTO','FACTURADO','ANULADO')),
    factura_id       BIGINT        REFERENCES factura(id),
    motivo_anulacion VARCHAR(200),
    usuario_id       BIGINT        REFERENCES usuario(id),
    creado_en        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_en   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_por  VARCHAR(45),
    version          BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_conduce_numero UNIQUE (compania_id, numero)
);
CREATE INDEX ix_conduce_cliente ON conduce (cliente_id, estado);

CREATE TABLE conduce_linea (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conduce_id            BIGINT        NOT NULL REFERENCES conduce(id) ON DELETE CASCADE,
    linea                 INT           NOT NULL,
    articulo_id           BIGINT        NOT NULL REFERENCES articulo(id),
    cantidad              NUMERIC(14,3) NOT NULL CHECK (cantidad > 0),
    precio_unitario       NUMERIC(18,4) NOT NULL CHECK (precio_unitario >= 0),   -- sin ITBIS, ya autorizado
    descuento_porcentaje  NUMERIC(5,2)  NOT NULL DEFAULT 0,
    costo_unitario        NUMERIC(18,4) NOT NULL DEFAULT 0
);

-- La factura generada desde conduces no vuelve a mover el inventario
ALTER TABLE factura ADD COLUMN desde_conduce BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE apartado (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id      BIGINT        NOT NULL REFERENCES compania(id),
    numero           BIGINT        NOT NULL,
    fecha            DATE          NOT NULL,
    cliente_id       BIGINT        NOT NULL REFERENCES cliente(id),
    concepto         VARCHAR(255)  NOT NULL,
    total            NUMERIC(18,2) NOT NULL DEFAULT 0,   -- con ITBIS, a los precios del apartado
    abonado          NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (abonado >= 0),
    fecha_limite     DATE,
    estado           VARCHAR(10)   NOT NULL DEFAULT 'ABIERTO' CHECK (estado IN ('ABIERTO','FACTURADO','CANCELADO')),
    factura_id       BIGINT        REFERENCES factura(id),
    motivo_cancelacion VARCHAR(200),
    usuario_id       BIGINT        REFERENCES usuario(id),
    creado_en        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_en   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_por  VARCHAR(45),
    version          BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_apartado_numero UNIQUE (compania_id, numero)
);

CREATE TABLE apartado_linea (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apartado_id           BIGINT        NOT NULL REFERENCES apartado(id) ON DELETE CASCADE,
    linea                 INT           NOT NULL,
    articulo_id           BIGINT        NOT NULL REFERENCES articulo(id),
    cantidad              NUMERIC(14,3) NOT NULL CHECK (cantidad > 0),
    precio_unitario       NUMERIC(18,4) NOT NULL CHECK (precio_unitario >= 0),
    descuento_porcentaje  NUMERIC(5,2)  NOT NULL DEFAULT 0
);

CREATE TABLE apartado_abono (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apartado_id      BIGINT        NOT NULL REFERENCES apartado(id),
    compania_id      BIGINT        NOT NULL REFERENCES compania(id),
    fecha            DATE          NOT NULL,
    tipo             VARCHAR(10)   NOT NULL DEFAULT 'ABONO' CHECK (tipo IN ('ABONO','DEVOLUCION')),
    forma_pago       VARCHAR(15)   NOT NULL CHECK (forma_pago IN ('EFECTIVO','TARJETA','CHEQUE','TRANSFERENCIA')),
    monto            NUMERIC(18,2) NOT NULL CHECK (monto > 0),
    referencia       VARCHAR(40),
    sesion_caja_id   BIGINT        REFERENCES caja_sesion(id),
    usuario_id       BIGINT        REFERENCES usuario(id),
    creado_en        TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX ix_apartado_abono ON apartado_abono (apartado_id);

CREATE TABLE plan_financiamiento (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id         BIGINT        NOT NULL REFERENCES compania(id),
    numero              BIGINT        NOT NULL,
    fecha               DATE          NOT NULL,
    factura_id          BIGINT        NOT NULL REFERENCES factura(id),
    cliente_id          BIGINT        NOT NULL REFERENCES cliente(id),
    pagado_previo       NUMERIC(18,2) NOT NULL DEFAULT 0,   -- cobrado de la factura antes del plan (inicial)
    capital             NUMERIC(18,2) NOT NULL CHECK (capital > 0),
    tasa_interes        NUMERIC(6,3)  NOT NULL DEFAULT 0,    -- % sobre el capital, por todo el plazo
    interes             NUMERIC(18,2) NOT NULL DEFAULT 0,
    nota_debito_id      BIGINT        REFERENCES nota_debito(id),
    cantidad_cuotas     INT           NOT NULL CHECK (cantidad_cuotas BETWEEN 1 AND 120),
    frecuencia_dias     INT           NOT NULL CHECK (frecuencia_dias IN (7, 15, 30)),
    mora_porcentaje     NUMERIC(6,3)  NOT NULL DEFAULT 0,    -- % de la cuota vencida, una vez por cuota
    dias_gracia         INT           NOT NULL DEFAULT 0 CHECK (dias_gracia >= 0),
    estado              VARCHAR(10)   NOT NULL DEFAULT 'ACTIVO' CHECK (estado IN ('ACTIVO','CANCELADO')),
    usuario_id          BIGINT        REFERENCES usuario(id),
    creado_en           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uk_plan_numero UNIQUE (compania_id, numero)
);
CREATE UNIQUE INDEX uk_plan_factura ON plan_financiamiento (factura_id) WHERE estado = 'ACTIVO';

CREATE TABLE plan_cuota (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id             BIGINT        NOT NULL REFERENCES plan_financiamiento(id) ON DELETE CASCADE,
    numero              INT           NOT NULL,
    vencimiento         DATE          NOT NULL,
    monto               NUMERIC(18,2) NOT NULL CHECK (monto > 0),
    mora_nota_debito_id BIGINT        REFERENCES nota_debito(id),   -- mora ya cobrada de esta cuota
    CONSTRAINT uk_plan_cuota UNIQUE (plan_id, numero)
);

INSERT INTO sub_menu (main_menu_id, nombre_opcion, codigo, ruta_frontend, orden)
SELECT m.id, o.nombre, o.codigo, o.ruta, o.orden
FROM (VALUES
  ('VENTAS', 'Conduces', 'VENTAS_CONDUCES', '/ventas/conduces', 4),
  ('VENTAS', 'Apartados', 'VENTAS_APARTADOS', '/ventas/apartados', 5),
  ('CXC', 'Ventas financiadas', 'CXC_FINANCIAMIENTO', '/cxc/financiamientos', 3)
) AS o(modulo, nombre, codigo, ruta, orden)
JOIN main_menu m ON m.codigo = o.modulo;
