-- Contador transaccional de numeración interna por compañía (factura, cotización, ...)
CREATE TABLE contador_documento (
    compania_id   BIGINT      NOT NULL REFERENCES compania(id),
    clave         VARCHAR(30) NOT NULL,
    ultimo        BIGINT      NOT NULL DEFAULT 0,
    PRIMARY KEY (compania_id, clave)
);

CREATE TABLE zona (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(45) NOT NULL UNIQUE,
    estado  VARCHAR(1)  NOT NULL DEFAULT 'A' CHECK (estado IN ('A','I'))
);

CREATE TABLE ciudad (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(60) NOT NULL,
    provincia        VARCHAR(60),
    estado           VARCHAR(1)  NOT NULL DEFAULT 'A' CHECK (estado IN ('A','I')),
    actualizado_en   TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_por  VARCHAR(45)
);

CREATE TABLE unidad (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(45) NOT NULL UNIQUE,
    abreviatura      VARCHAR(10),
    estado           VARCHAR(1)  NOT NULL DEFAULT 'A' CHECK (estado IN ('A','I')),
    actualizado_en   TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_por  VARCHAR(45)
);

CREATE TABLE turno (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(45) NOT NULL,
    estado           VARCHAR(1)  NOT NULL DEFAULT 'A' CHECK (estado IN ('A','I')),
    actualizado_en   TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_por  VARCHAR(45)
);

CREATE TABLE departamento (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id        BIGINT      NOT NULL REFERENCES compania(id),
    nombre             VARCHAR(45) NOT NULL,
    tipo               VARCHAR(1)  NOT NULL DEFAULT 'I' CHECK (tipo IN ('I','S','E')), -- Inventario, Servicio, Empleado
    cuenta_costo       VARCHAR(12),
    cuenta_ingreso     VARCHAR(12),
    cuenta_inventario  VARCHAR(12),
    estado             VARCHAR(1)  NOT NULL DEFAULT 'A' CHECK (estado IN ('A','I')),
    actualizado_en     TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_por    VARCHAR(45)
);
CREATE INDEX ix_departamento_compania ON departamento (compania_id);

CREATE TABLE almacen (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id      BIGINT      NOT NULL REFERENCES compania(id),
    nombre           VARCHAR(45) NOT NULL,
    ubicacion        VARCHAR(100),
    principal        BOOLEAN     NOT NULL DEFAULT FALSE,
    estado           VARCHAR(1)  NOT NULL DEFAULT 'A' CHECK (estado IN ('A','I')),
    actualizado_en   TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_por  VARCHAR(45)
);
CREATE UNIQUE INDEX uk_almacen_principal ON almacen (compania_id) WHERE principal;

-- Vendedor: en el legacy se creaba con el mismo id del usuario (call agrega_vendedor)
CREATE TABLE vendedor (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id      BIGINT        NOT NULL REFERENCES compania(id),
    usuario_id       BIGINT        UNIQUE REFERENCES usuario(id),
    nombre           VARCHAR(90)   NOT NULL,
    rnc_cedula       VARCHAR(11),
    fecha_nacimiento DATE,
    comision         NUMERIC(5,2)  NOT NULL DEFAULT 0 CHECK (comision BETWEEN 0 AND 100),
    ciudad_id        BIGINT        REFERENCES ciudad(id),
    direccion        VARCHAR(150),
    correo           VARCHAR(100),
    telefono         VARCHAR(20),
    estado           VARCHAR(1)    NOT NULL DEFAULT 'A' CHECK (estado IN ('A','I')),
    actualizado_en   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_por  VARCHAR(45)
);

CREATE TABLE cliente (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id         BIGINT        NOT NULL REFERENCES compania(id),
    nombre              VARCHAR(150)  NOT NULL,          -- razón social o nombre completo
    rnc_cedula          VARCHAR(11),                      -- 9 (RNC) u 11 (cédula) dígitos, sin guiones
    -- e-CF: tipo de comprobante por defecto (legacy clientex.tiponcf: 01->31, 02->32, 14->44, 15->45)
    tipo_ecf_preferido  SMALLINT      NOT NULL DEFAULT 32 CHECK (tipo_ecf_preferido IN (31,32,44,45)),
    exento_itbis        BOOLEAN       NOT NULL DEFAULT FALSE,   -- legacy libreimpuesto
    tipo_precio         VARCHAR(10)   NOT NULL DEFAULT 'CONTADO' CHECK (tipo_precio IN ('CONTADO','CREDITO','MAYOR')),
    limite_credito      NUMERIC(18,2) NOT NULL DEFAULT 0,
    dias_credito        INTEGER       NOT NULL DEFAULT 0,
    ciudad_id           BIGINT        REFERENCES ciudad(id),
    zona_id             BIGINT        REFERENCES zona(id),
    direccion           VARCHAR(150),
    correo              VARCHAR(100),
    telefono            VARCHAR(20),
    celular             VARCHAR(20),
    contacto            VARCHAR(100),
    cuenta_contable     VARCHAR(12),
    estado              VARCHAR(1)    NOT NULL DEFAULT 'A' CHECK (estado IN ('A','I')),
    actualizado_en      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_por     VARCHAR(45),
    version             BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT ck_cliente_rnc CHECK (rnc_cedula IS NULL OR rnc_cedula ~ '^(\d{9}|\d{11})$'),
    CONSTRAINT ck_cliente_cf  CHECK (tipo_ecf_preferido = 32 OR rnc_cedula IS NOT NULL)
);
CREATE UNIQUE INDEX uk_cliente_rnc ON cliente (compania_id, rnc_cedula) WHERE rnc_cedula IS NOT NULL;
CREATE INDEX ix_cliente_nombre ON cliente (compania_id, lower(nombre));

CREATE TABLE proveedor (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id      BIGINT       NOT NULL REFERENCES compania(id),
    nombre           VARCHAR(150) NOT NULL,
    rnc_cedula       VARCHAR(11),
    direccion        VARCHAR(255),
    sector           VARCHAR(60),
    ciudad_id        BIGINT       REFERENCES ciudad(id),
    correo           VARCHAR(100),
    telefono         VARCHAR(20),
    contacto         VARCHAR(100),
    cuenta_contable  VARCHAR(12),
    estado           VARCHAR(1)   NOT NULL DEFAULT 'A' CHECK (estado IN ('A','I')),
    actualizado_en   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actualizado_por  VARCHAR(45),
    CONSTRAINT ck_proveedor_rnc CHECK (rnc_cedula IS NULL OR rnc_cedula ~ '^(\d{9}|\d{11})$')
);
CREATE UNIQUE INDEX uk_proveedor_rnc ON proveedor (compania_id, rnc_cedula) WHERE rnc_cedula IS NOT NULL;

