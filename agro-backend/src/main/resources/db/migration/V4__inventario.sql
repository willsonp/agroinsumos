-- =====================================================================
-- V4: Inventario
-- Cambio de diseño: el legacy NO guardaba existencias; las recalculaba en cada
-- consulta sumando todo el historial (proc. ConsultaCantidad_Articulo).
-- Ahora: kardex (inventario_movimiento, inmutable) + existencia por almacén,
-- actualizados en la misma transacción que el documento que los origina.
-- Origen: articulo, precio, invalmacen, ajuste/detalle_ajuste,
--         transentsalida/detalle_transentsalidad
-- =====================================================================

CREATE TABLE articulo (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id           BIGINT        NOT NULL REFERENCES compania(id),
    codigo_barra          VARCHAR(20),
    referencia            VARCHAR(20),
    nombre                VARCHAR(80)   NOT NULL,          -- máx. NombreItem del e-CF
    descripcion           VARCHAR(500),
    tipo                  VARCHAR(1)    NOT NULL DEFAULT 'B' CHECK (tipo IN ('B','S')),  -- Bien (inventariable) / Servicio
    departamento_id       BIGINT        NOT NULL REFERENCES departamento(id),
    unidad_id             BIGINT        NOT NULL REFERENCES unidad(id),
    proveedor_id          BIGINT        REFERENCES proveedor(id),
    -- 1 ITBIS 18%, 2 ITBIS 16%, 3 ITBIS 0%, 4 Exento (IndicadorFacturacion del e-CF)
    indicador_itbis       SMALLINT      NOT NULL DEFAULT 1 CHECK (indicador_itbis BETWEEN 1 AND 4),
    costo                 NUMERIC(18,4) NOT NULL DEFAULT 0,   -- último costo
    costo_promedio        NUMERIC(18,4) NOT NULL DEFAULT 0,   -- promedio ponderado
    -- Precios SIN ITBIS con 4 decimales: permiten reproducir exactamente un precio final
    -- con ITBIS (el legacy guardaba precios CON ITBIS: base = precio / 1.18).
    precio_contado        NUMERIC(18,4) NOT NULL DEFAULT 0,
    precio_credito        NUMERIC(18,4) NOT NULL DEFAULT 0,
    precio_mayor          NUMERIC(18,4) NOT NULL DEFAULT 0,
    descuento_maximo      NUMERIC(5,2)  NOT NULL DEFAULT 0 CHECK (descuento_maximo BETWEEN 0 AND 100),
    stock_minimo          NUMERIC(14,3) NOT NULL DEFAULT 0,
    ubicacion             VARCHAR(50),
    imagen_url            VARCHAR(255),
    estado                VARCHAR(1)    NOT NULL DEFAULT 'A' CHECK (estado IN ('A','I')),
    actualizado_en        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_por       VARCHAR(45),
    version               BIGINT        NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX uk_articulo_codigo_barra ON articulo (compania_id, codigo_barra) WHERE codigo_barra IS NOT NULL;
CREATE INDEX ix_articulo_nombre ON articulo (compania_id, lower(nombre));

-- Existencia actual por artículo y almacén (fila bloqueada con FOR UPDATE al moverla)
CREATE TABLE existencia (
    articulo_id  BIGINT        NOT NULL REFERENCES articulo(id),
    almacen_id   BIGINT        NOT NULL REFERENCES almacen(id),
    cantidad     NUMERIC(14,3) NOT NULL DEFAULT 0,
    PRIMARY KEY (articulo_id, almacen_id)
);

-- Kardex: cada entrada/salida, con su documento de origen. Nunca se modifica ni borra.
CREATE TABLE inventario_movimiento (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id      BIGINT        NOT NULL REFERENCES compania(id),
    articulo_id      BIGINT        NOT NULL REFERENCES articulo(id),
    almacen_id       BIGINT        NOT NULL REFERENCES almacen(id),
    fecha            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    tipo             VARCHAR(25)   NOT NULL CHECK (tipo IN ('SALDO_INICIAL','COMPRA','VENTA','DEVOLUCION_VENTA',
                                   'DEVOLUCION_COMPRA','AJUSTE_ENTRADA','AJUSTE_SALIDA','ENTRADA','SALIDA',
                                   'TRANSFERENCIA_ENTRADA','TRANSFERENCIA_SALIDA')),
    cantidad         NUMERIC(14,3) NOT NULL CHECK (cantidad <> 0),   -- + entrada, - salida
    costo_unitario   NUMERIC(18,4) NOT NULL DEFAULT 0,
    existencia_final NUMERIC(14,3) NOT NULL,
    documento_tipo   VARCHAR(30)   NOT NULL,
    documento_id     BIGINT        NOT NULL,
    usuario          VARCHAR(45)
);
CREATE INDEX ix_kardex_articulo ON inventario_movimiento (articulo_id, fecha);
CREATE INDEX ix_kardex_documento ON inventario_movimiento (documento_tipo, documento_id);

-- Documento de inventario: unifica ajuste (teórico vs físico), entradas/salidas manuales
-- (transentsalida) y transferencias entre almacenes. Flujo: BORRADOR -> APLICADO (o ANULADO).
CREATE TABLE documento_inventario (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id         BIGINT       NOT NULL REFERENCES compania(id),
    numero              BIGINT       NOT NULL,
    tipo                VARCHAR(15)  NOT NULL CHECK (tipo IN ('AJUSTE','ENTRADA','SALIDA','TRANSFERENCIA')),
    fecha               DATE         NOT NULL,
    almacen_id          BIGINT       NOT NULL REFERENCES almacen(id),
    almacen_destino_id  BIGINT       REFERENCES almacen(id),
    descripcion         VARCHAR(200),
    estado              VARCHAR(10)  NOT NULL DEFAULT 'BORRADOR' CHECK (estado IN ('BORRADOR','APLICADO','ANULADO')),
    aplicado_en         TIMESTAMPTZ,
    aplicado_por        VARCHAR(45),
    actualizado_en      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actualizado_por     VARCHAR(45),
    version             BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_docinv_numero UNIQUE (compania_id, numero),
    CONSTRAINT ck_docinv_transfer CHECK ((tipo = 'TRANSFERENCIA') = (almacen_destino_id IS NOT NULL)),
    CONSTRAINT ck_docinv_destino CHECK (almacen_destino_id IS NULL OR almacen_destino_id <> almacen_id)
);

CREATE TABLE documento_inventario_linea (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_id      BIGINT        NOT NULL REFERENCES documento_inventario(id) ON DELETE CASCADE,
    articulo_id       BIGINT        NOT NULL REFERENCES articulo(id),
    cantidad          NUMERIC(14,3) NOT NULL,   -- ENTRADA/SALIDA/TRANSFERENCIA: > 0; AJUSTE: conteo físico (>= 0)
    cantidad_teorica  NUMERIC(14,3),            -- AJUSTE: existencia al aplicar
    costo_unitario    NUMERIC(18,4),
    CONSTRAINT ck_docinv_cantidad CHECK (cantidad >= 0)
);
CREATE INDEX ix_docinv_linea ON documento_inventario_linea (documento_id);
