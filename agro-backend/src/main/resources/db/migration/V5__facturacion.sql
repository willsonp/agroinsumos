-- =====================================================================
-- V5: Facturación (ventas) integrada con e-CF
-- Origen: factura, detalle_factura, cotizacion, detalle_cotizacion,
--         devolucion, detalle_devolucion
-- Estructura nueva para e-CF:
--   * factura.ecf_documento_id / devolucion.ecf_documento_id -> ecf_documento
--   * factura.ncf_legacy: NCF en papel/secuencial (B01, B02...) de facturas migradas
--   * Toda devolución emite una Nota de Crédito electrónica (34) referenciada
-- =====================================================================

CREATE TABLE factura (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id        BIGINT        NOT NULL REFERENCES compania(id),
    numero             BIGINT        NOT NULL,
    fecha              DATE          NOT NULL,
    condicion          VARCHAR(10)   NOT NULL CHECK (condicion IN ('CONTADO','CREDITO')),  -- legacy TipoFactura A/E
    dias_credito       INTEGER       NOT NULL DEFAULT 0,
    fecha_vencimiento  DATE,
    cliente_id         BIGINT        NOT NULL REFERENCES cliente(id),
    cliente_nombre     VARCHAR(150)  NOT NULL,     -- copia histórica (el cliente puede cambiar)
    cliente_rnc        VARCHAR(11),
    vendedor_id        BIGINT        REFERENCES vendedor(id),
    almacen_id         BIGINT        NOT NULL REFERENCES almacen(id),
    tipo_precio        VARCHAR(10)   NOT NULL,
    comentario         VARCHAR(600),
    numero_orden       VARCHAR(30),
    monto_gravado      NUMERIC(18,2) NOT NULL DEFAULT 0,
    monto_exento       NUMERIC(18,2) NOT NULL DEFAULT 0,
    total_descuento    NUMERIC(18,2) NOT NULL DEFAULT 0,
    total_itbis        NUMERIC(18,2) NOT NULL DEFAULT 0,
    total              NUMERIC(18,2) NOT NULL,
    balance            NUMERIC(18,2) NOT NULL,     -- pendiente de cobro (Caja / CxC)
    costo_total        NUMERIC(18,2) NOT NULL DEFAULT 0,
    -- Comprobante fiscal
    tipo_ecf           SMALLINT,
    encf               VARCHAR(13),
    ecf_documento_id   BIGINT        REFERENCES ecf_documento(id),
    ncf_legacy         VARCHAR(19),
    cotizacion_id      BIGINT,
    estado             VARCHAR(12)   NOT NULL DEFAULT 'EMITIDA' CHECK (estado IN ('EMITIDA','PAGADA','ANULADA')),
    creado_en          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    usuario_id         BIGINT        REFERENCES usuario(id),
    actualizado_en     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_por    VARCHAR(45),
    version            BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_factura_numero UNIQUE (compania_id, numero),
    CONSTRAINT ck_factura_balance CHECK (balance >= 0 AND balance <= total)
);
CREATE UNIQUE INDEX uk_factura_encf ON factura (compania_id, encf) WHERE encf IS NOT NULL;
CREATE INDEX ix_factura_cliente ON factura (cliente_id, fecha);
CREATE INDEX ix_factura_fecha ON factura (compania_id, fecha);
CREATE INDEX ix_factura_pendiente ON factura (cliente_id) WHERE balance > 0 AND estado <> 'ANULADA';

CREATE TABLE factura_linea (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    factura_id           BIGINT        NOT NULL REFERENCES factura(id) ON DELETE CASCADE,
    linea                INTEGER       NOT NULL,
    articulo_id          BIGINT        NOT NULL REFERENCES articulo(id),
    descripcion          VARCHAR(80)   NOT NULL,
    unidad               VARCHAR(20),
    cantidad             NUMERIC(14,3) NOT NULL CHECK (cantidad > 0),
    precio_unitario      NUMERIC(18,4) NOT NULL CHECK (precio_unitario >= 0),
    descuento            NUMERIC(18,2) NOT NULL DEFAULT 0,
    indicador_itbis      SMALLINT      NOT NULL,
    tasa_itbis           NUMERIC(5,2)  NOT NULL,
    importe              NUMERIC(18,2) NOT NULL,   -- cantidad*precio - descuento (sin ITBIS)
    itbis                NUMERIC(18,2) NOT NULL,
    costo_unitario       NUMERIC(18,4) NOT NULL DEFAULT 0,
    cantidad_devuelta    NUMERIC(14,3) NOT NULL DEFAULT 0,
    CONSTRAINT uk_factura_linea UNIQUE (factura_id, linea),
    CONSTRAINT ck_devuelta CHECK (cantidad_devuelta BETWEEN 0 AND cantidad)
);

CREATE TABLE cotizacion (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id       BIGINT        NOT NULL REFERENCES compania(id),
    numero            BIGINT        NOT NULL,
    fecha             DATE          NOT NULL,
    valida_hasta      DATE,
    cliente_id        BIGINT        NOT NULL REFERENCES cliente(id),
    vendedor_id       BIGINT        REFERENCES vendedor(id),
    tipo_precio       VARCHAR(10)   NOT NULL,
    comentario        VARCHAR(600),
    total_itbis       NUMERIC(18,2) NOT NULL DEFAULT 0,
    total             NUMERIC(18,2) NOT NULL DEFAULT 0,
    estado            VARCHAR(12)   NOT NULL DEFAULT 'ABIERTA' CHECK (estado IN ('ABIERTA','FACTURADA','ANULADA')),
    factura_id        BIGINT        REFERENCES factura(id),
    actualizado_en    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_por   VARCHAR(45),
    version           BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_cotizacion_numero UNIQUE (compania_id, numero)
);
ALTER TABLE factura ADD CONSTRAINT fk_factura_cotizacion FOREIGN KEY (cotizacion_id) REFERENCES cotizacion(id);

CREATE TABLE cotizacion_linea (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cotizacion_id    BIGINT        NOT NULL REFERENCES cotizacion(id) ON DELETE CASCADE,
    linea            INTEGER       NOT NULL,
    articulo_id      BIGINT        NOT NULL REFERENCES articulo(id),
    cantidad         NUMERIC(14,3) NOT NULL CHECK (cantidad > 0),
    precio_unitario  NUMERIC(18,4) NOT NULL,
    descuento        NUMERIC(18,2) NOT NULL DEFAULT 0,
    importe          NUMERIC(18,2) NOT NULL,
    itbis            NUMERIC(18,2) NOT NULL
);

CREATE TABLE devolucion (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id       BIGINT        NOT NULL REFERENCES compania(id),
    numero            BIGINT        NOT NULL,
    fecha             DATE          NOT NULL,
    factura_id        BIGINT        NOT NULL REFERENCES factura(id),
    motivo            VARCHAR(90)   NOT NULL,
    -- e-CF 34: 1 anula totalmente, 3 corrige montos (devolución parcial)
    codigo_modificacion SMALLINT    NOT NULL CHECK (codigo_modificacion IN (1,3)),
    total_itbis       NUMERIC(18,2) NOT NULL,
    total             NUMERIC(18,2) NOT NULL,
    aplicado_a_balance NUMERIC(18,2) NOT NULL DEFAULT 0,  -- reduce la CxC de la factura
    saldo_a_favor     NUMERIC(18,2) NOT NULL DEFAULT 0,   -- crédito del cliente (o reembolso en caja)
    encf              VARCHAR(13),
    ecf_documento_id  BIGINT        REFERENCES ecf_documento(id),
    estado            VARCHAR(10)   NOT NULL DEFAULT 'EMITIDA' CHECK (estado IN ('EMITIDA')),
    usuario_id        BIGINT        REFERENCES usuario(id),
    actualizado_en    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_por   VARCHAR(45),
    CONSTRAINT uk_devolucion_numero UNIQUE (compania_id, numero)
);
CREATE INDEX ix_devolucion_factura ON devolucion (factura_id);

CREATE TABLE devolucion_linea (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    devolucion_id     BIGINT        NOT NULL REFERENCES devolucion(id) ON DELETE CASCADE,
    factura_linea_id  BIGINT        NOT NULL REFERENCES factura_linea(id),
    cantidad          NUMERIC(14,3) NOT NULL CHECK (cantidad > 0),
    importe           NUMERIC(18,2) NOT NULL,
    itbis             NUMERIC(18,2) NOT NULL,
    reingresa_inventario BOOLEAN    NOT NULL DEFAULT TRUE
);

-- Saldo a favor del cliente (nota de crédito no aplicada). Se consumirá desde CxC / Caja.
ALTER TABLE cliente ADD COLUMN saldo_a_favor NUMERIC(18,2) NOT NULL DEFAULT 0;
