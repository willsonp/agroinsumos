-- Impresoras de etiquetas en red (Zebra y compatibles ZPL, puerto RAW 9100)
CREATE TABLE impresora_etiqueta (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compania_id      BIGINT       NOT NULL REFERENCES compania(id),
    nombre           VARCHAR(60)  NOT NULL,
    host             VARCHAR(100) NOT NULL,
    puerto           INT          NOT NULL DEFAULT 9100 CHECK (puerto BETWEEN 9100 AND 9109),
    dpi              INT          NOT NULL DEFAULT 203 CHECK (dpi IN (203, 300, 600)),
    ancho_mm         NUMERIC(6,1) NOT NULL DEFAULT 50.8,
    alto_mm          NUMERIC(6,1) NOT NULL DEFAULT 25.4,
    estado           VARCHAR(1)   NOT NULL DEFAULT 'A' CHECK (estado IN ('A','I')),
    actualizado_en   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actualizado_por  VARCHAR(45),
    CONSTRAINT uk_impresora_etiqueta UNIQUE (compania_id, nombre)
);

-- Parámetros generales del sistema (p.ej. carpeta de respaldos)
CREATE TABLE parametro_sistema (
    clave           VARCHAR(60)  PRIMARY KEY,
    valor           VARCHAR(500) NOT NULL,
    actualizado_en  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actualizado_por VARCHAR(45)
);

INSERT INTO sub_menu (main_menu_id, nombre_opcion, codigo, ruta_frontend, orden)
SELECT m.id, o.nombre, o.codigo, o.ruta, o.orden
FROM (VALUES
  ('INVENTARIO', 'Imprimir etiquetas', 'INV_ETIQUETAS', '/inventario/etiquetas', 3),
  ('ADMIN', 'Respaldos de la base de datos', 'ADMIN_RESPALDOS', '/admin/respaldos', 2)
) AS o(modulo, nombre, codigo, ruta, orden)
JOIN main_menu m ON m.codigo = o.modulo;
